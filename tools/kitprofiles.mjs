// Side profiles of the kit-built hulls for the crew cutaway (src/game/ship/kitProfiles.js), from the JSON dumps
// of the kits. Run after rebuilding a kit:   node tools/kitprofiles.mjs
// tests/kit.test.mjs fails when the file is out of date with the kit.
import fs from 'node:fs';
import { CHASSIS } from '../src/game/data/chassis.js';
import { CLASS_LAYOUT, indexKit, planHull, kitSideProfile } from '../src/game/ship/kitPlan.js';

const dir = new URL('../assets/ships/kits/', import.meta.url);
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json'))) {
  const kit = indexKit(JSON.parse(fs.readFileSync(new URL(f, dir))));
  for (const c of CHASSIS) {
    if (c.yard !== kit.lang || !CLASS_LAYOUT[c.tier] || c.kit || c.livery) continue;
    const plan = planHull(c, kit);
    if (plan.ok) out[c.id] = kitSideProfile(plan);
  }
}
const body = Object.entries(out).map(([id, p]) => `  ${id}: ${JSON.stringify(p)},`).join('\n');
fs.writeFileSync(new URL('../src/game/ship/kitProfiles.js', import.meta.url),
  `// Generated by tools/kitprofiles.mjs from assets/ships/kits/*.json: do not edit. The side silhouette of every hull\n// built from a part kit (kitPlan.js kitSideProfile), which hullPlan.js sideProfile() hands to the crew cutaway.\nexport const KIT_PROFILES = {\n${body}\n};\n`);
console.log(`${Object.keys(out).length} kit profiles`);
